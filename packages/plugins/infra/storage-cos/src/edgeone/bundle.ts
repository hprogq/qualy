import { fileURLToPath } from 'node:url'

// The edge function as the platform takes it: one classic script, every
// import inlined, nothing left for the runtime to resolve.
//
// Built from ./entry.ts, so the function that runs at the edge is the module
// the tests exercise and the protocol the server signs with, not a copy of
// them. esbuild is a development dependency and is loaded only here: this is
// run from a checkout, never by the serving process.

const ENTRY = fileURLToPath(new URL('./entry.ts', import.meta.url))
const WEBCRYPTO = fileURLToPath(new URL('./webcrypto.ts', import.meta.url))

/** the bundled script's text */
export const bundleEdgeFunction = async (): Promise<string> => {
  const { build } = await import('esbuild')
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    // the web build of the token library: WebCrypto and nothing of node's
    conditions: ['browser'],
    // every bundled reference to the global `crypto` reaches the runtime's
    // WebCrypto through the module that makes it answer as the standard does
    inject: [WEBCRYPTO],
    legalComments: 'inline',
    minify: false,
    charset: 'utf8',
  })
  const output = result.outputFiles[0]
  if (output === undefined) throw new Error('the edge function bundle came out empty')
  return `// @qualy/plugin-storage-cos edge delivery - generated by \`qualy cos edge-build\`; edit src/edgeone, not this\n${output.text}`
}
