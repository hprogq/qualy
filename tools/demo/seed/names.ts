export const makeNames = (random: Random) => {
  const used = new Set<string>()
  const surnames = SURNAMES.map(([surname, weight]) => ({ surname, weight }))
  return () => {
    for (;;) {
      const surname = random.weighted(surnames).surname
      const length = random.chance(0.72) ? 2 : 1
      let given = ''
      for (let i = 0; i < length; i++) given += random.pick(GIVEN)
      const name = surname + given
      if (given.length === 2 && given[0] === given[1]) continue
      if (!used.has(name)) {
        used.add(name)
        return name
      }
    }
  }
}
